function buildHome(ui, locale) {
	const meta = PAGE_META_HOME[locale];
	const connectors = HOME_CONNECTORS[locale];
	if (!meta || !connectors) return {};
	const store = ui.nav.pricing;
	const status = ui.nav.updates;
	return {
		aboutTitle: meta.h1,
		aboutP1: `${meta.intro} ${store} · ${status}.`,
		...connectors,
	};
}

